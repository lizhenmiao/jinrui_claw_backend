create table if not exists support_report (
  id bigint not null auto_increment comment 'Primary key',
  report_no varchar(64) not null comment 'Client-generated receipt id (idempotent on retry)',
  license_id bigint null comment 'licenses.id',
  device_id bigint null comment 'devices.id',
  license_key varchar(64) null comment 'Client license key',
  usb_id varchar(128) null comment 'Client USB id',
  machine_id varchar(128) null comment 'Client machine id',
  hostname varchar(128) null comment 'Host name',
  os_name varchar(128) null comment 'Operating system',
  arch varchar(32) null comment 'CPU architecture',
  client_version varchar(64) null comment 'Client version',
  scene varchar(32) not null default 'manual' comment 'repair_failed/reset_failed/startup_failed/update_failed/manual/other',
  error_code varchar(64) null comment 'Client error code',
  error_summary varchar(1024) null comment 'Error summary',
  remark varchar(512) null comment 'User description',
  contact varchar(128) null comment 'User contact, optional',
  file_path varchar(512) null comment 'Stored zip relative path under report dir',
  file_size bigint null comment 'Zip size in bytes',
  file_sha256 char(64) null comment 'Zip SHA256',
  source_ip varchar(64) null comment 'Upload request IP',
  status varchar(16) not null default 'submitted' comment 'submitted/triaged/resolved/ignored',
  admin_note varchar(1024) null comment 'Admin note',
  created_at datetime not null comment 'Created time',
  updated_at datetime not null comment 'Updated time',
  primary key (id),
  unique key uk_support_report_no (report_no),
  key idx_support_report_scene_created (scene, created_at),
  key idx_support_report_status_created (status, created_at),
  key idx_support_report_license_key (license_key),
  key idx_support_report_client_version (client_version)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='Client support reports (diagnostic log bundles)';